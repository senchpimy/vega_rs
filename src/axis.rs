pub fn is_axis_property(prop: &str) -> bool {
    AXIS_PROPERTIES.contains(&prop)
}

pub fn is_conditional_axis_value(value: &Value) -> bool {
    match value {
        Value::Object(_) => has_property(value, "condition") || has_property(value, "expr"),
        Value::Array(_) => true,
        _ => false,
    }
}
